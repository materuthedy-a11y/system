'use client';

import type { SalesInvoice } from '@/lib/api/sales';
import { calendarDateLabel, money } from '@/components/sales/SalesPrimitives';

interface Props {
  invoice: SalesInvoice;
  businessName?: string;
  businessLogoUrl?: string | null;
}

export function InvoicePrintReceipt({ invoice, businessName, businessLogoUrl }: Props) {
  return (
    <div className="print-area hidden bg-white text-black" aria-hidden="true">
      <div className="mx-auto w-[72mm] font-mono text-[11px] leading-tight">
        {businessLogoUrl ? (
          <div className="mb-1 flex justify-center"><img src={businessLogoUrl} alt="" className="h-12 w-12 object-contain" /></div>
        ) : null}
        <div className="text-center">
          <p className="text-sm font-bold">{businessName || 'Mizania Business'}</p>
          <p className="font-bold uppercase tracking-widest">Tax Invoice / Receipt</p>
        </div>
        <div className="my-2 border-t border-dashed border-black" />
        <table className="w-full">
          <tbody>
            <tr><td>Invoice</td><td className="text-right font-bold">{invoice.invoiceNumber}</td></tr>
            <tr><td>Date</td><td className="text-right">{calendarDateLabel(invoice.invoiceDate)}</td></tr>
            {invoice.dueDate ? <tr><td>Due</td><td className="text-right">{calendarDateLabel(invoice.dueDate)}</td></tr> : null}
            <tr><td>Customer</td><td className="text-right">{invoice.customerName}</td></tr>
            <tr><td>Location</td><td className="text-right">{invoice.locationName}</td></tr>
            <tr><td>Status</td><td className="text-right uppercase">{invoice.status.replace(/_/g, ' ')}</td></tr>
          </tbody>
        </table>
        <div className="my-2 border-t border-dashed border-black" />
        <table className="w-full">
          <thead>
            <tr className="border-b border-black text-left">
              <th className="py-1">Item</th>
              <th className="py-1 text-right">Qty</th>
              <th className="py-1 text-right">Total</th>
            </tr>
          </thead>
          <tbody>
            {invoice.items.map((item) => (
              <tr key={item.id} className="align-top">
                <td className="py-1 pr-1">
                  {item.productName}
                  <span className="block text-[9px] opacity-70">{item.productSku} · {money(item.unitPrice, invoice.currency)} × {item.quantity}{item.discountPercentage ? ` · -${item.discountPercentage}%` : ''}</span>
                </td>
                <td className="py-1 text-right">{item.quantity}</td>
                <td className="py-1 text-right">{money(item.lineTotal, invoice.currency)}</td>
              </tr>
            ))}
          </tbody>
        </table>
        <div className="my-2 border-t border-dashed border-black" />
        <table className="w-full">
          <tbody>
            <tr><td>Subtotal</td><td className="text-right">{money(invoice.subtotal, invoice.currency)}</td></tr>
            {invoice.discountAmount > 0 ? <tr><td>Discount</td><td className="text-right">-{money(invoice.discountAmount, invoice.currency)}</td></tr> : null}
            {invoice.taxAmount > 0 ? <tr><td>Tax</td><td className="text-right">{money(invoice.taxAmount, invoice.currency)}</td></tr> : null}
            <tr className="font-bold"><td>TOTAL</td><td className="text-right">{money(invoice.totalAmount, invoice.currency)}</td></tr>
            {invoice.totalPaid > 0 ? <tr><td>Paid</td><td className="text-right">{money(invoice.totalPaid, invoice.currency)}</td></tr> : null}
            {invoice.returnCredits > 0 ? <tr><td>Returns</td><td className="text-right">-{money(invoice.returnCredits, invoice.currency)}</td></tr> : null}
            {invoice.balance !== invoice.totalAmount ? <tr className="font-bold"><td>BALANCE</td><td className="text-right">{money(invoice.balance, invoice.currency)}</td></tr> : null}
          </tbody>
        </table>
        {invoice.notes ? <p className="mt-2 whitespace-pre-wrap">{invoice.notes}</p> : null}
        <div className="my-2 border-t border-dashed border-black" />
        <p className="text-center">Thank you for your business.</p>
        <p className="text-center text-[9px] opacity-60">Generated by Mizania · {new Date().toLocaleString()}</p>
      </div>
    </div>
  );
}
